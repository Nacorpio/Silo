namespace Silo;

/// <summary>Where the icon of a <see cref="TabHeader"/> goes relative to its text.</summary>
public enum IconPosition
{
    /// <summary>The icon is left of the text. This is the default.</summary>
    Left,

    /// <summary>The icon is above the text.</summary>
    Top,

    /// <summary>The icon is right of the text.</summary>
    Right,
}
