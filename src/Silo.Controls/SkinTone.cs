namespace Silo;

/// <summary>
/// The skin tone that an emoji with people or body parts in it is shown in.
/// </summary>
public enum SkinTone
{
    /// <summary>The default, yellow emoji.</summary>
    Default,

    /// <summary>Light skin tone.</summary>
    Light,

    /// <summary>Medium-light skin tone.</summary>
    MediumLight,

    /// <summary>Medium skin tone.</summary>
    Medium,

    /// <summary>Medium-dark skin tone.</summary>
    MediumDark,

    /// <summary>Dark skin tone.</summary>
    Dark,
}
